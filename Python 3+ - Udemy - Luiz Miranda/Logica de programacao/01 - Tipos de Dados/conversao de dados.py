# conversão de tipos, coerção, type convertion, typecasting ou coercion
# é o ato de converter um tipo de dado em outro
#  tipos imutáveis e primitivos:
# str, int, float, bool

# print("1" + 1)
print(int("1") + 1)
print(float("1") + 1)

print(type(int("1")))
print(type(float("1")))

print(bool(" "))
print(bool(""))

print(str(11) + "a")
print(str(5.5) + "b")

print(type(str(11)))
print(type(str(5.5)))
